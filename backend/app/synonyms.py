_NOISE = re.compile(r"\s+")


def expand(query: str, max_terms: int = 12) -> List[str]:
    """คำค้นเพิ่มจากวลีใน query (ว่าง = ไม่มีวลีที่รู้จัก) — วลียาวกว่าได้ก่อน ตัดซ้ำ คงลำดับ"""
    q = _NOISE.sub("", (query or "").casefold())
    if not q:
        return []
    out: List[str] = []
    for phrase in sorted(SYNONYMS, key=len, reverse=True):
        if phrase.replace(" ", "") in q:
            for t in SYNONYMS[phrase]:
                if t not in out:
                    out.append(t)
    return out[:max_terms]
